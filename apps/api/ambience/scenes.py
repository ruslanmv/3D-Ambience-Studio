_NO_PEOPLE = "Empty environment art with no people of any kind."


def _scene(
    scene_id: str,
    name: str,
    category: str,
    tags: list[str],
    subject: str,
    lighting: dict[str, Any],
    fallback: str,
    description: str = "",
) -> dict[str, Any]:
    return {
        "id": scene_id,
        "version": "1.0.0",
        "name": name,
        "description": description,
        "category": category,
        "tags": tags,
        "fallbackColor": fallback,
        "lighting": lighting,
        "subject": f"{subject} {_ORIGINAL} {_NO_PEOPLE}",
    }


