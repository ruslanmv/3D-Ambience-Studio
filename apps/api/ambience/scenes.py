"""The built-in scene presets: art direction only.

Ten scenes, and not one camera figure among them. Every number a plate is composed against — the
horizon, the foot anchor, the keep-clear band, the field of view — is read from the runtime's
camera contract at generation time and compiled into the prompt by `plate_package`. That split is
the point of this file: adding a scene is writing a paragraph, and changing the camera is
re-exporting a contract. Neither touches the other.

The temptation it exists to resist is to paste "feet at 89.7%" into each entry so the prompts read
completely. Ten copies of a measurement is ten places to miss when the camera moves, and the
failure is silent — the art still generates, it just no longer fits.

## What a `subject` is

The artistic half, written as if briefing a photographer who will never see the avatar: what the
place is, what time it is, where the light comes from, what is in the foreground. It must not
describe the character, the safe zone or the geometry; `build_prompt` appends all of that.

Two rules are in every subject rather than in the compiler, because they are art direction rather
than geometry: **an original place**, not a recognisable real or fictional one, and **a usable
standing surface** in the foreground. A scene that is beautiful and has nowhere to stand is the
characteristic failure of this whole route — scenic wallpaper with the character pasted onto it.

## `lighting`

An approximation the runtime can actually reproduce with a key light, a hemisphere fill and an
exposure. It is not a description of the picture; it is the three-value summary a Three.js scene
can be set up from, so the avatar is lit roughly the way the plate behind her is.
"""

